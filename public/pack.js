// Стандартный пакет: 4 раунда по 6 тем собираются из базы (bank.js), остальные темы лежат в запасе.
(function () {
  const B = window.QUESTION_BANK;
  const mkTheme = ([name, desc, qs, kind]) => ({
    name, desc: desc || '',
    questions: qs.map(([text, answer], i) => ({ type: kind === 'closest' ? 'closest' : 'normal', text, answer, media: null, answerMedia: null, modifier: '', value: 0, diff: i + 1 })),
  });
  const byName = n => { const t = B.find(x => x[0] === n); if (!t) throw new Error('Нет темы в базе: ' + n); return t; };

  // [название раунда, случайных модификаторов, темы, особые клетки [тема, вопрос, тип]]
  const plan = [
    ['Разминка', 2, ['-ПОГ-', 'Фильм в двух словах', 'Что в бокале', 'Секс-просвет 18+', 'Животные: правда или миф?', 'Фразы, которые все слышали'], [[2, 3, 'auction']]],
    ['Разгон', 2, ['-ДОМ-', 'Анаграммы', 'Чей слоган?', 'Были женаты?', 'Допиши: кино', 'Ближе всех'], [[1, 2, 'cat'], [3, 3, 'auction']]],
    ['Без тормозов', 3, ['-КОН-', 'Сериал в двух словах', 'Все — Александры', 'Пьяная история', 'Ого! Факты', 'Как это называется?'], [[0, 3, 'cat'], [4, 2, 'cat'], [5, 3, 'auction']]],
    ['Ва-банк', 3, ['Анаграммы 2.0', 'Все — Михаилы', 'Отношения 18+', 'Деньги', 'География с подвохом', 'Ближе всех 2.0'], [[2, 2, 'cat'], [4, 3, 'cat'], [0, 4, 'auction']]],
  ];
  const used = new Set();
  const rounds = plan.map(([name, randomMods, themes, special]) => {
    const r = { name, randomMods, themes: themes.map(n => { used.add(n); return mkTheme(byName(n)); }) };
    special.forEach(([ti, qi, type]) => { const q = r.themes[ti].questions[qi]; q.type = type; if (type === 'cat') q.cat = { theme: '', value: 0 }; });
    return r;
  });
  const bank = B.filter(t => !used.has(t[0])).map(mkTheme);

  const F = (name, text, answer) => ({ name, text, answer, media: null, answerMedia: null });
  // 12 сложных тем: игроки по очереди убирают по одной, на последнюю делают ставки
  const finalHard = [
    F('Кино', 'Какой фильм первым получил «Оскар» как лучший фильм, будучи снятым не на английском языке?', '«Паразиты» (2020)'),
    F('Космос', 'Какая звезда ближе всех к Солнцу?', 'Проксима Центавра'),
    F('География', 'Ватикан и Сан-Марино целиком окружены другой страной. Какое третье такое государство находится в Африке?', 'Лесото (внутри ЮАР)'),
    F('Тело человека', 'Какую железу в мозге называют «третьим глазом»? Она вырабатывает гормон сна мелатонин', 'Эпифиз (шишковидная железа)'),
    F('Алкоголь', 'Сколько лет как минимум виски должен выдерживаться в дубовой бочке, чтобы называться шотландским (скотчем)?', '3 года'),
    F('Музыка', 'Какой композитор написал «Болеро» и сам называл его «пьесой для оркестра без музыки»?', 'Морис Равель'),
    F('Литература', 'Какой русский писатель утверждал, что это он ввёл в язык слово «стушеваться»?', 'Фёдор Достоевский'),
    F('Животные', 'Какое крошечное животное выжило в открытом космосе без всякой защиты?', 'Тихоходка'),
    F('Бренды', 'Какая компания, прежде чем делать суперкары, выпускала тракторы?', 'Lamborghini'),
    F('История', 'Как звали единственную женщину, правившую Китаем как императрица в своём праве?', 'У Цзэтянь (VII век)'),
    F('18+', 'Как назывался древнеримский праздник плодородия 15 февраля, с которым часто связывают День святого Валентина?', 'Луперкалии'),
    F('Еда', 'Какую самую дорогую в мире специю добывают из рыльцев цветка крокуса?', 'Шафран'),
  ];
  window.FINAL_HARD = finalHard;
  // прежний стандартный финал — по нему игра узнаёт, что финал не трогали, и сама заменяет его на новый
  window.FINAL_OLD_NAMES = ['Кино', 'Химия', 'Алкоголь', 'Анатомия', 'Русский язык', 'Космос', 'Секс-символы'];
  const final = { themes: JSON.parse(JSON.stringify(finalHard)) };

  const M = (id, emoji, name, desc, type, amount, hidden) => ({ id, emoji, name, desc, type, amount: amount || 0, enabled: true, hidden: !!hidden });
  const modifiers = [
    M('m-sign', '±', 'Плюс на минус', 'Поменяй знак счёта любому игроку: себе или сопернику', 'signflip'),
    M('m-steal', '💰', 'Грабёж', 'Забери 2000 у кого угодно', 'steal', 2000),
    M('m-immune', '😇', 'Бессмертие', 'До конца раунда неверные ответы не отнимают очки', 'immune'),
    M('m-double', '⚡', 'Двойной удар', 'До конца раунда за верные ответы — ×2', 'double'),
    M('m-swap', '🔄', 'Обмен', 'Поменяйся счётом с любым игроком', 'swap'),
    M('m-shield', '🛡️', 'Щит', 'Следующий неверный ответ не будет стоить очков', 'shield'),
    M('m-gift', '🎁', 'Подарок', '+1000 просто так', 'add', 1000),
    M('m-bomb', '💣', 'Бомба', 'Ой. Кто схватил — теряет 1000', 'add', -1000, true),
    M('m-tax', '🧾', 'Налог', 'Все остальные платят по 500', 'tax', 500),
    M('m-crown', '👑', 'Корона', 'Следующий вопрос выбираешь ты', 'chooser'),
    M('m-approx', '🤏', 'Приблизительно', 'До конца раунда можешь отвечать приблизительно — ведущий засчитывает «почти»', 'custom'),
    M('m-compl', '💐', 'Комплимент', 'Сделай ведущему три комплимента — и получишь подсказку на любой вопрос', 'custom'),
  ];

  window.DEFAULT_PACK = { name: 'Своя тусовка 18+', version: 2, builtin: true, rounds, final, modifiers, bank };
})();
